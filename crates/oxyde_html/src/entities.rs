/// Longueur maximale d'un nom de la table.
pub(crate) const MAX_NAME_LEN: usize = 8;

/// Cherche le nom exact `name` (sans `&` ni `;`).
pub(crate) fn lookup(name: &str) -> Option<&'static str> {
    TABLE.iter().find(|(n, _)| *n == name).map(|(_, v)| *v)
}

/// Vrai si `name` est valide sans point-virgule final.
pub(crate) fn is_legacy(name: &str) -> bool {
    LEGACY.contains(&name)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn table_is_consistent() {
        for (name, _) in TABLE {
            assert!(name.len() <= MAX_NAME_LEN, "{name} dépasse MAX_NAME_LEN");
        }
        for name in LEGACY {
            assert!(lookup(name).is_some(), "{name} absent de la table");
        }
        assert_eq!(lookup("eacute"), Some("é"));
        assert_eq!(lookup("inconnu"), None);
    }
}
